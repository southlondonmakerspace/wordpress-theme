/*
 * Builds static/js/map-style.js: the MapLibre style for the front-page map.
 *
 * The look is "drafting paper": warm off-white land, graphite lines and
 * labels, quiet greens and blues, with the makerspace red kept for the main
 * roads' casing and the marker so the space stands out.
 *
 * Run after changing colours:  npm run map-style
 */
'use strict';

var fs = require( 'fs' );
var path = require( 'path' );
var basemaps = require( '@protomaps/basemaps' );

var paper    = '#f4f1ec';
var graphite = '#3b3835';
var pencil   = '#7d766d';
var rule     = '#dcd5ca';
var green    = '#dfe5d5';
var green2   = '#d3dcc6';
var blue     = '#c8d8de';
var brick    = '#e6e0d7';
var redLine  = '#f1b8a8';
var redFill  = '#fde9e3';

var flavor = Object.assign( {}, basemaps.namedFlavor( 'light' ), {
	background: paper,
	earth: paper,
	park_a: green, park_b: green2,
	wood_a: green, wood_b: green2,
	scrub_a: green, scrub_b: green2,
	zoo: green, glacier: paper, sand: '#ece6da', beach: '#ece6da',
	hospital: '#efe7e3', school: '#eee9df', industrial: '#e8e4dd',
	pedestrian: '#ebe6dd', aerodrome: '#e9e6e0', runway: '#f8f6f2', military: '#e9e6e0',
	water: blue,
	buildings: brick,
	pier: rule,

	other: '#f7f5f1', minor_service: '#f7f5f1', minor_a: '#fbfaf7', minor_b: '#ffffff', link: '#ffffff',
	major: '#ffffff', highway: redFill,
	minor_service_casing: rule, minor_casing: rule, link_casing: rule,
	major_casing_early: '#cfc7bb', major_casing_late: '#cfc7bb',
	highway_casing_early: redLine, highway_casing_late: redLine,
	railway: '#9a948b',
	boundaries: '#b9b2a7',

	bridges_other_casing: rule, bridges_minor_casing: rule, bridges_link_casing: rule,
	bridges_major_casing: '#cfc7bb', bridges_highway_casing: redLine,
	bridges_other: '#f7f5f1', bridges_minor: '#ffffff', bridges_link: '#ffffff',
	bridges_major: '#ffffff', bridges_highway: redFill,

	tunnel_other_casing: rule, tunnel_minor_casing: rule, tunnel_link_casing: rule,
	tunnel_major_casing: rule, tunnel_highway_casing: redLine,
	tunnel_other: '#efebe5', tunnel_minor: '#efebe5', tunnel_link: '#efebe5',
	tunnel_major: '#efebe5', tunnel_highway: '#f6e3dd',

	roads_label_minor: pencil, roads_label_minor_halo: '#ffffff',
	roads_label_major: pencil, roads_label_major_halo: '#ffffff',
	address_label: pencil, address_label_halo: '#ffffff',
	ocean_label: '#6f8a94',
	subplace_label: pencil, subplace_label_halo: paper,
	city_label: graphite, city_label_halo: paper,
	state_label: pencil, state_label_halo: paper,
	country_label: pencil,

	landcover: {
		grassland: green, barren: '#ece6da', urban_area: '#eeeae4',
		farmland: green, glacier: paper, scrub: green, forest: green2
	}
} );

// Points of interest are left out: they need an icon sprite, and the map
// should only point at one place.
var layers = basemaps.layers( 'protomaps', flavor, { lang: 'en' } )
	.filter( function ( layer ) { return layer[ 'source-layer' ] !== 'pois'; } );

// Except park names, as text alone: they help find the way. Placed under the
// neighbourhood names, so those win where they meet.
var parkLabels = {
	id: 'pois_park_labels',
	type: 'symbol',
	source: 'protomaps',
	'source-layer': 'pois',
	filter: [ 'in', 'kind', 'park', 'nature_reserve' ],
	layout: {
		'text-field': [ 'coalesce', [ 'get', 'name:en' ], [ 'get', 'name' ] ],
		'text-font': [ 'Noto Sans Italic' ],
		'text-size': 11,
		'text-max-width': 8
	},
	paint: {
		'text-color': '#5b6e4d',
		'text-halo-color': paper,
		'text-halo-width': 1.5
	}
};

layers.splice( layers.findIndex( function ( layer ) { return layer.id === 'places_subplace'; } ), 0, parkLabels );

var out = '/* Generated by static/map/build-style.js. Do not edit by hand. */\n' +
	'window.slmsMapLayers = ' + JSON.stringify( layers ) + ';\n';

fs.writeFileSync( path.join( __dirname, '..', 'js', 'map-style.js' ), out );
console.log( 'Wrote static/js/map-style.js (' + layers.length + ' layers)' );
